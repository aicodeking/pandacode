fn log(dir: &Path, cwd: &Path) -> PathBuf {
    let project = dir.join("projects").join("-tmp-demo");
    std::fs::create_dir_all(project.join(SESSION).join("subagents")).unwrap();
    let line = |value: serde_json::Value| value.to_string();
    let lines = [
        line(json!({"type":"permission-mode","permissionMode":"default","sessionId":SESSION})),
        line(json!({"type":"user","sessionId":SESSION,"cwd":cwd,"timestamp":"2026-09-20T10:00:00.250Z","isMeta":true,"message":{"role":"user","content":"Caveat: The messages below were generated by the user"}})),
        line(json!({"type":"user","sessionId":SESSION,"cwd":cwd,"timestamp":"2026-09-20T10:00:01.000Z","message":{"role":"user","content":"Fix the login redirect loop\nwhen sessions expire"}})),
        line(json!({"type":"assistant","sessionId":SESSION,"cwd":cwd,"timestamp":"2026-09-20T10:00:05.000Z","message":{"role":"assistant","model":"claude-opus-5-5","content":[{"type":"thinking","thinking":"private"},{"type":"text","text":"I'll look at the auth middleware."},{"type":"tool_use","name":"Read","input":{"file_path":"/secret/path"}}]}})),
        line(json!({"type":"user","sessionId":SESSION,"cwd":cwd,"timestamp":"2026-09-20T10:00:06.000Z","message":{"role":"user","content":[{"type":"tool_result","content":"file contents"}]}})),
        line(json!({"type":"user","sessionId":SESSION,"cwd":cwd,"timestamp":"2026-09-20T10:00:07.000Z","message":{"role":"user","content":"<command-name>/clear</command-name>"}})),
        line(json!({"type":"assistant","sessionId":SESSION,"cwd":cwd,"isSidechain":true,"timestamp":"2026-09-20T10:00:08.000Z","message":{"role":"assistant","content":[{"type":"text","text":"subagent chatter"}]}})),
        line(json!({"type":"assistant","sessionId":SESSION,"cwd":cwd,"timestamp":"2026-09-20T10:01:00.000Z","message":{"role":"assistant","model":"claude-opus-5-5","content":[{"type":"text","text":"Fixed: the refresh token is now rotated."}]}})),
        line(json!({"type":"ai-title","aiTitle":"Fix login redirect loop","sessionId":SESSION})),
    ];
    let path = project.join(format!("{SESSION}.jsonl"));
    std::fs::write(&path, lines.join("\n") + "\n").unwrap();
    std::fs::write(project.join(SESSION).join("subagents").join("agent-1.jsonl"), lines[3].clone() + "\n").unwrap();
    path
}

fn temp() -> PathBuf {
    let dir = std::env::temp_dir().join(format!("pandacode-import-{}", uuid::Uuid::new_v4()));
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn claude_summary_uses_ai_title_and_counts_only_readable_main_thread_messages() {
    let dir = temp();
    let path = log(&dir, &dir);
    let summary = claude::summarize(&path).unwrap();
    assert_eq!(summary.session_id, SESSION);
    assert_eq!(summary.title, "Fix login redirect loop");
    assert_eq!(summary.cwd, dir.to_string_lossy());
    assert_eq!(summary.messages, 3, "meta, tool results, slash-command echoes and sidechains are skipped");
    assert_eq!(summary.model.as_deref(), Some("claude-opus-5-5"));
    assert_eq!(summary.created_at % 1000, 0);
    assert!(summary.updated_at > summary.created_at);
    assert_eq!(claude::logs(&[dir.join("projects")], 10), vec![path], "subagent logs are not separate conversations");
    std::fs::remove_dir_all(dir).unwrap();
}

