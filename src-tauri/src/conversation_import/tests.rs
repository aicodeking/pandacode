#[test]
fn importing_adds_the_folder_project_keeps_times_and_is_found_again() {
    let dir = temp();
    let path = log(&dir, &dir);
    let summary = claude::summarize(&path).unwrap();
    let store = Store::open(Path::new(":memory:")).unwrap();
    let project = project_for(&store, &summary.cwd).unwrap();
    assert_eq!(project_for(&store, &summary.cwd).unwrap(), project, "the same folder maps to the same project");
    let task = store.import_task(&project, "claude", "claude-opus-5-5", &summary.title, SESSION, None, summary.created_at, &claude::history(&path)).unwrap();
    assert_eq!(task.resume_id.as_deref(), Some(SESSION));
    assert_eq!(task.title, "Fix login redirect loop");
    assert_eq!(task.created_at, summary.created_at);
    assert_eq!(task.last_response_at, Some(summary.updated_at));
    assert!(!task.draft);
    assert_eq!(store.imported_task("claude", SESSION).unwrap(), Some(task.id.clone()));
    assert_eq!(store.imported_task("codex", SESSION).unwrap(), None);
    assert!(store.sessions().unwrap().iter().any(|listed| listed.id == task.id));
    assert!(project_for(&store, "/definitely/missing/folder").is_err());
    assert!(project_for(&store, "").is_err());
    std::fs::remove_dir_all(dir).unwrap();
}

